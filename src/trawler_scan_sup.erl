%%%-------------------------------------------------------------------
%%% @doc Динамический supervisor координаторов сканирований.
%%%
%%% Зарегистрирован локально под именем `trawler_scan_sup'. Содержит
%%% временных (temporary) дочерних процессов {@link trawler_scan},
%%% которые добавляются через `supervisor:start_child/2' на время
%%% одного сканирования. Поскольку дети временные, сбой координатора
%%% не приводит к незаметному перезапуску сетевой работы.
%%%
%%% Интенсивность перезапусков равна нулю: динамические дети не
%%% перезапускаются, а ошибка инфраструктуры не размножается.
%%% @end
%%%-------------------------------------------------------------------
-module(trawler_scan_sup).

-behaviour(supervisor).

%% Публичный API
-export([start_link/0]).
%% Обратные вызовы supervisor
-export([init/1]).

%%% ------------------------------------------------------------------
%%% Публичный API
%%% ------------------------------------------------------------------

%% @doc Запускает supervisor под локальным именем `trawler_scan_sup'.
-spec start_link() -> {ok, pid()} | {error, term()}.
start_link() ->
    supervisor:start_link({local, ?MODULE}, ?MODULE, []).

%%% ------------------------------------------------------------------
%%% Обратные вызовы supervisor
%%% ------------------------------------------------------------------

%% @doc Задаёт стратегию `one_for_one' без перезапусков и пустой список
%% статических детей: координаторы добавляются динамически.
-spec init([]) -> {ok, {supervisor:sup_flags(), [supervisor:child_spec()]}}.
init([]) ->
    Flags = #{strategy => one_for_one, intensity => 0, period => 1},
    {ok, {Flags, []}}.
